def _block(text: str, tag: str):
    m = re.search(rf"<{tag}>(.*?)</{tag}>", text, re.S | re.I)
    if m:
        return m.group(1).strip()
    m = re.search(rf"<{tag}>(.*?)(?=<(?:analysis|status|answer|extra|sources)>|\Z)", text, re.S | re.I)
    return m.group(1).strip() if m else None


def parse_output(raw: str) -> dict:
    """Extract status, answer and cited sources from the model output (tolerant to format slips)."""
    text = raw.strip()
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.S | re.I).strip()
    answer = _block(text, "answer")
    status_raw = (_block(text, "status") or "").upper()
    status = next((s for s in STATUSES if s in status_raw), "")
    sources = []
    for line in (_block(text, "sources") or "").split("\n"):
        line = line.strip().lstrip("-•* ").strip()
        if not line or "|" not in line:
            continue
        cells = [c.strip() for c in line.split("|")]
        doc_id = re.sub(r"[\[\]\s]", "", cells[0]).upper()
        if not re.fullmatch(r"[DL]\d{1,3}", doc_id):
            continue
        locator = cells[1] if len(cells) > 1 else ""
        quote = " | ".join(cells[2:]).strip().strip("«»\"'") if len(cells) > 2 else ""
        sources.append({"doc_id": doc_id, "locator": locator, "quote": quote})
    if answer is None:
        # no tags at all: treat the whole text as the answer, dropping any stray markup
        stripped = re.sub(r"</?(analysis|status|answer|extra|sources)>", " ", text, flags=re.I)
        analysis_block = _block(text, "analysis")
        if analysis_block:
            stripped = stripped.replace(analysis_block, " ")
        answer = stripped.strip()
    answer = drop_unfinished(clean_answer(answer))
    extra = drop_unfinished(clean_answer(_block(text, "extra") or ""))
    if extra.lower().strip(" .-—") in ("", "пусто", "нет", "отсутствует", "не требуется"):
        extra = ""
    return {"status": status or "ANSWER", "answer": answer, "extra": extra, "sources": sources,
            "analysis": _block(text, "analysis") or "", "well_formed": bool(status)}


ANSWER_WORD_CAP = 90           # only true outliers: reference answers stay well below; steps and calculations get more room
LONG_ANSWER_WORD_CAP = 140


def trim_answer(answer: str):
    """Safety net against rare long answers: keep leading sentences within a word cap.

    Returns (kept, dropped). The first sentence (the direct answer) always stays; a closing
    "Источник: ..." sentence is kept as well. Enumerated steps and calculations get a higher cap.
    """
    from la_text import sentences
    sents = sentences(answer)
    if len(sents) < 2:
        return answer, ""
    roomy = bool(re.search(r"\b1\)\s.*\b2\)\s", answer)) or bool(re.search(r"\d\s*[=×]\s*\d", answer))
    cap = LONG_ANSWER_WORD_CAP if roomy else ANSWER_WORD_CAP
    if len(answer.split()) <= cap:
        return answer, ""
    kept, dropped, used = [], [], 0
    for i, sent in enumerate(sents):
        size = len(sent.split())
        if not dropped and (i == 0 or used + size <= cap):
            kept.append(sent)
            used += size
        else:
            dropped.append(sent)
    if dropped and dropped[-1].lower().startswith("источник") and len(dropped[-1].split()) <= 16:
        kept.append(dropped.pop())
    return " ".join(kept), " ".join(dropped)


def drop_unfinished(answer: str) -> str:
    """An answer cut off by the token limit keeps only its complete sentences."""
    text = answer.rstrip()
    if not text or re.search(r"[.!?»)\]…]$", text):
        return text
    from la_text import sentences
    sents = sentences(text)
    if len(sents) > 1:
        return " ".join(sents[:-1])
    return text


def clean_answer(answer: str) -> str:
    a = re.sub(r"\s*\[(?:[DL]\d{1,3})(?:\s*,\s*[DL]\d{1,3})*\]", "", answer)      # service labels
    a = re.sub(r"\*\*(.+?)\*\*", r"\1", a)                                          # markdown bold
    a = re.sub(r"^\s*#+\s*", "", a, flags=re.M)
    a = re.sub(r"\s+", " ", a).strip()
    a = re.sub(r"\s+([,.;:!?])", r"\1", a)
    return a


def locator_keys(locator: str) -> tuple:
    """Numeric keys of a citation: 'п. 1, подп. 2.1' -> ('1', '2.1'); 'примечание 2' -> ('прим', '2')."""
    s = locator.lower().replace("ё", "е")
    s = re.sub(r"ст(?:атья|атьи|\.)\s*\d+(?:\.\d+)*", " ", s)     # the article number is not a unit key
    keys = re.findall(r"\d+(?:\.\d+)*(?:-\d+)?", s)
    if "примеч" in s:
        return ("прим",) + tuple(keys[:1])
    return tuple(keys[:2])


