# Parsing the model output
# --------------------------------------------------------------------------- #

def _block(text: str, tag: str):
    m = re.search(rf"<{tag}>(.*?)</{tag}>", text, re.S | re.I)
    if m:
        return m.group(1).strip()
    m = re.search(rf"<{tag}>(.*?)(?=<(?:analysis|status|answer|sources)>|\Z)", text, re.S | re.I)
    return m.group(1).strip() if m else None


def parse_output(raw: str) -> dict:
    """Extract status, answer and cited sources from the model output (tolerant to format slips)."""
    text = raw.strip()
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.S | re.I).strip()
    answer = _block(text, "answer")
    status_raw = (_block(text, "status") or "").upper()
    status = next((s for s in STATUSES if s in status_raw), "")
    sources = []
    for line in (_block(text, "sources") or "").split("\n"):
        line = line.strip().lstrip("-•* ").strip()
        if not line or "|" not in line:
            continue
        cells = [c.strip() for c in line.split("|")]
        doc_id = re.sub(r"[\[\]\s]", "", cells[0]).upper()
        if not re.fullmatch(r"[DL]\d{1,3}", doc_id):
            continue
        locator = cells[1] if len(cells) > 1 else ""
        quote = " | ".join(cells[2:]).strip().strip("«»\"'") if len(cells) > 2 else ""
        sources.append({"doc_id": doc_id, "locator": locator, "quote": quote})
    if answer is None:
        # no tags at all: treat the whole text as the answer, dropping any stray markup
        stripped = re.sub(r"</?(analysis|status|answer|sources)>", " ", text, flags=re.I)
        analysis_block = _block(text, "analysis")
        if analysis_block:
            stripped = stripped.replace(analysis_block, " ")
        answer = stripped.strip()
    answer = clean_answer(answer)
    return {"status": status or "ANSWER", "answer": answer, "sources": sources,
            "analysis": _block(text, "analysis") or "", "well_formed": bool(status)}


def clean_answer(answer: str) -> str:
    a = re.sub(r"\s*\[(?:[DL]\d{1,3})(?:\s*,\s*[DL]\d{1,3})*\]", "", answer)      # service labels
    a = re.sub(r"\*\*(.+?)\*\*", r"\1", a)                                          # markdown bold
    a = re.sub(r"^\s*#+\s*", "", a, flags=re.M)
    a = re.sub(r"\s+", " ", a).strip()
    a = re.sub(r"\s+([,.;:!?])", r"\1", a)
    return a


def locator_keys(locator: str) -> tuple:
    """Numeric keys of a citation: 'п. 1, подп. 2.1' -> ('1', '2.1'); 'примечание 2' -> ('прим', '2')."""
    s = locator.lower().replace("ё", "е")
    s = re.sub(r"ст(?:атья|атьи|\.)\s*\d+(?:\.\d+)*", " ", s)     # the article number is not a unit key
    keys = re.findall(r"\d+(?:\.\d+)*(?:-\d+)?", s)
    if "примеч" in s:
        return ("прим",) + tuple(keys[:1])
    return tuple(keys[:2])


